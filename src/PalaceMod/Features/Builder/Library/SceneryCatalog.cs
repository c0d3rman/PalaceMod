using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using Newtonsoft.Json;

/*
    The cross-map scenery catalog: src/PalaceMod/Assets/scenery.json, generated by scripts/scenery_catalog.py
    (`dev.py scenery-catalog`) from the installed game. Metadata only: each scenery mesh of the main maps, the asset
    file and object it lives in, the maps that use it, its category, materials and how the maps place it. The meshes
    themselves are read from the player's install at runtime (SceneryLibrary).

    Refs: a prop's base is "mesh:<name>", optionally "mesh:<name>@<Map>" to say which map's mesh is meant if two maps
    ever have one by the same name. Pure C# so it's unit-testable.
*/
namespace PalaceMod.Builder.Library
{
    internal sealed class SceneryEntry
    {
        [JsonProperty("name")] public string Name;
        /// <summary>The scene that uses it most (a scene name, e.g. "Neuland(Tutorial)").</summary>
        [JsonProperty("home")] public string Home;
        /// <summary>Scene name → how many times that map places it.</summary>
        [JsonProperty("maps")] public Dictionary<string, int> Maps = [];
        [JsonProperty("file")] public string File;
        [JsonProperty("pathId")] public long PathId;
        [JsonProperty("category")] public string Category;
        /// <summary>Material names, one per submesh, matched by name to the loaded level's own materials.</summary>
        [JsonProperty("materials")] public List<string> Materials = [];
        /// <summary>The maps' typical rotation without its yaw (x, y, z, w).</summary>
        [JsonProperty("upright")] public float[] Upright;
        /// <summary>The maps' typical scale.</summary>
        [JsonProperty("scale")] public float[] Scale;
        [JsonProperty("scaleSpread")] public float ScaleSpread;
        [JsonProperty("vertices")] public int Vertices;
        /// <summary>The mesh's own bounds size (before scale).</summary>
        [JsonProperty("size")] public float[] Size;

        /// <summary>"mesh:&lt;name&gt;".</summary>
        public string Ref => SceneryCatalog.Prefix + Name;
    }

    internal sealed class SceneryCatalog
    {
        public const string Prefix = "mesh:";

        [JsonProperty("unity")] public string Unity;
        [JsonProperty("maps")] public List<string> Maps = [];
        [JsonProperty("meshes")] public List<SceneryEntry> Meshes = [];

        public static SceneryCatalog Parse(string json)
        {
            var c = JsonConvert.DeserializeObject<SceneryCatalog>(json) ?? throw new InvalidDataException("empty catalog");
            c.Meshes = c.Meshes.Where(m => m != null && !string.IsNullOrEmpty(m.Name) && !string.IsNullOrEmpty(m.File)).ToList();
            return c;
        }

        public static SceneryCatalog FromResource()
        {
            using var stream = typeof(SceneryCatalog).Assembly.GetManifestResourceStream("PalaceMod.Assets.scenery.json")
                ?? throw new FileNotFoundException("scenery.json isn't embedded");
            using var reader = new StreamReader(stream);
            return Parse(reader.ReadToEnd());
        }

        /// <summary>The entry a ref names: by name, and by map when the ref has "@Map" (the map must use it).</summary>
        public SceneryEntry Find(string baseRef)
        {
            if (!TryParseRef(baseRef, out var name, out var map)) return null;
            var matches = Meshes.Where(m => m.Name == name);
            if (map != null) matches = matches.Where(m => m.Home == map || m.Maps.ContainsKey(map) || DisplayMap(m.Home) == map);
            return matches.FirstOrDefault();
        }

        /// <summary>Splits "mesh:&lt;name&gt;[@&lt;Map&gt;]". False if it isn't a mesh ref or the name is empty.</summary>
        public static bool TryParseRef(string baseRef, out string name, out string map)
        {
            name = map = null;
            if (baseRef == null || !baseRef.StartsWith(Prefix, StringComparison.Ordinal)) return false;
            name = baseRef.Substring(Prefix.Length);
            int at = name.LastIndexOf('@');
            if (at >= 0)
            {
                map = name.Substring(at + 1);
                name = name.Substring(0, at);
                if (map.Length == 0) map = null;
            }
            return name.Length > 0;
        }

        /// <summary>A scene name as players know the map: "Neuland(Tutorial)" → "Neuland".</summary>
        public static string DisplayMap(string scene)
        {
            if (scene == null) return null;
            int paren = scene.IndexOf('(');
            return (paren > 0 ? scene.Substring(0, paren) : scene).Trim();
        }
    }
}
